# 7. Convert a protein sequence to lowercase and count amino acids
#
# Expected Output:
# Lowercase: mvkftlailvag
# Length: 12
# Number of Alanine (A): 2

protein = "MVKFTLAILVAG"
print("Lowercase:", protein.lower())
print("Length:", len(protein))
print("Number of Alanine (A):", protein.count("A"))
